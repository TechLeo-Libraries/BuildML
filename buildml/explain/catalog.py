def _operation(
    name: str,
    kind: OperationKind,
    definition: str,
    purpose: str,
    role: str,
    mechanism: tuple[str, ...],
    *,
    parameters: tuple[ParameterSpec, ...] = (),
    inputs: tuple[str, ...],
    outputs: tuple[str, ...],
    prerequisites: tuple[Prerequisite, ...] = (),
    ordering: tuple[str, ...],
    alternatives: tuple[str, ...],
    rationale: tuple[str, ...],
    assumptions: tuple[str, ...],
    failures: tuple[str, ...],
    leakage: tuple[str, ...],
    anti_patterns: tuple[str, ...],
    state_changes: tuple[str, ...],
    result_reading: tuple[str, ...],
    next_steps: tuple[str, ...],
    concepts: tuple[str, ...],
) -> OperationSpec:
    unknown = set(concepts) - CONCEPT_NOTES.keys()
    if unknown:
        raise ValueError(f"{name} links unknown concepts: {sorted(unknown)}")
    return OperationSpec(
        name=name,
        kind=kind,
        definition=definition,
        purpose=purpose,
        pipeline_role=role,
        mechanism=mechanism,
        parameters=parameters,
        inputs=inputs,
        outputs=outputs,
        prerequisites=prerequisites,
        usual_ordering=ordering,
        alternatives=alternatives,
        selection_rationale=rationale,
        assumptions=assumptions,
        failure_modes=failures,
        leakage_risks=leakage,
        anti_patterns=anti_patterns,
        state_changes=state_changes,
        result_reading=result_reading,
        next_considerations=next_steps,
        concept_links=concepts,
    )


