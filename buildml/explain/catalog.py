def _p(
    name: str,
    type_name: str,
    description: str,
    default: object = None,
    *,
    required: bool = False,
    choices: tuple[str, ...] = (),
) -> ParameterSpec:
    return ParameterSpec(
        name=name,
        type_name=type_name,
        description=description,
        required=required,
        default=default,  # type: ignore[arg-type]
        choices=choices,
    )


